using System.Globalization;
using System.Text;

namespace Oxygen.Editor.Schemas.Generators;

/// <summary>Renders the editor code of each output of the scene components schema.</summary>
internal static class SceneComponentsEmitter
{
    /// <summary>The runtime's component and field ids.</summary>
    public const string WireIds = "WireIds";

    /// <summary>The scene component kinds and typed property ids.</summary>
    public const string PropertyIds = "PropertyIds";

    /// <summary>The live preview's table of each property's engine component, fields and encoding.</summary>
    public const string WireTable = "WireTable";

    /// <summary>Gets every output name.</summary>
    public static IReadOnlyList<string> Outputs { get; } = [WireIds, PropertyIds, WireTable];

    /// <summary>Renders one output.</summary>
    /// <param name="output">One of <see cref="Outputs"/>.</param>
    /// <param name="schema">The schema.</param>
    /// <returns>The hint name and the source text.</returns>
    public static (string HintName, string Source) Render(string output, SceneComponentsSchema schema)
        => output switch
        {
            WireIds => ("SceneWireIds.g.cs", RenderWireIds(schema)),
            PropertyIds => ("SceneSchema.g.cs", RenderPropertyIds(schema)),
            WireTable => ("SceneWire.g.cs", RenderWireTable(schema)),
            _ => throw new ArgumentOutOfRangeException(nameof(output), output, "unknown output"),
        };

    private static StringBuilder Header(string ns)
        => new StringBuilder()
            .AppendLine("// <auto-generated>")
            .AppendLine("// Generated by SceneComponentsGenerator from SceneComponents.yaml; do not edit.")
            .AppendLine("// </auto-generated>")
            .AppendLine()
            .AppendLine("#nullable enable")
            .AppendLine()
            .Append("namespace ").Append(ns).AppendLine(";");

    private static string RenderWireIds(SceneComponentsSchema schema)
    {
        var source = Header("Oxygen.Editor.Runtime.Engine")
            .AppendLine()
            .AppendLine("/// <summary>The scene components the engine takes field by field: the coarse dimension of a runtime property.</summary>")
            .AppendLine("public enum RuntimeComponentId : ushort")
            .AppendLine("{")
            .AppendLine("    /// <summary>Sentinel; not a valid wire id.</summary>")
            .AppendLine("    Invalid = 0,");
        foreach (var component in schema.Components.Where(static component => component.Wire is not null).OrderBy(static component => component.Wire!.Id))
        {
            _ = source.AppendLine()
                .Append("    /// <summary>The <c>").Append(component.Kind).AppendLine("</c> component.</summary>")
                .Append("    ").Append(component.Name).Append(" = ").Append(Number(component.Wire!.Id)).AppendLine(",");
        }

        _ = source.AppendLine("}");
        foreach (var fieldSet in schema.FieldSets)
        {
            _ = source.AppendLine()
                .Append("/// <summary>Component-local field ids of the ").Append(fieldSet.Name).AppendLine(" field set.</summary>")
                .Append("public enum ").Append(fieldSet.Name).AppendLine("Field : ushort")
                .AppendLine("{");
            var first = true;
            foreach (var field in fieldSet.Fields.OrderBy(static field => field.Id))
            {
                _ = (first ? source : source.AppendLine())
                    .Append("    /// <summary>Field ").Append(Number(field.Id)).Append(" of the ").Append(fieldSet.Name).AppendLine(" field set.</summary>")
                    .Append("    ").Append(field.Name).Append(" = ").Append(Number(field.Id)).AppendLine(",");
                first = false;
            }

            _ = source.AppendLine("}");
        }

        return source.ToString();
    }

    private static string RenderPropertyIds(SceneComponentsSchema schema)
    {
        var source = Header("Oxygen.Editor.Scenes.Properties")
            .AppendLine()
            .AppendLine("/// <summary>The scene components: each one's kind and the typed ids of its properties.</summary>")
            .AppendLine("public static class SceneSchema")
            .AppendLine("{");
        var first = true;
        foreach (var component in schema.Components)
        {
            _ = (first ? source : source.AppendLine())
                .Append("    /// <summary>The <c>").Append(component.Kind).AppendLine("</c> component.</summary>")
                .Append("    public static class ").AppendLine(component.Name)
                .AppendLine("    {")
                .AppendLine("        /// <summary>The component kind.</summary>")
                .Append("        public const string Kind = \"").Append(component.Kind).AppendLine("\";");
            foreach (var property in component.Properties)
            {
                var type = "global::Oxygen.Editor.Schemas.PropertyId<" + SceneComponentsTypes.EditorType(property) + ">";
                _ = source.AppendLine()
                    .Append("        /// <summary>Gets the <c>").Append(property.Key).AppendLine("</c> property.</summary>")
                    .Append("        public static ").Append(type).Append(' ').Append(property.Name)
                    .Append(" { get; } = new(Kind, \"").Append(property.Key).AppendLine("\");");
            }

            _ = source.AppendLine("    }");
            first = false;
        }

        return source.AppendLine("}").ToString();
    }

    private static string RenderWireTable(SceneComponentsSchema schema)
    {
        var source = Header("Oxygen.Editor.LivePreview.Scenes")
            .AppendLine()
            .AppendLine("/// <content>The engine component, fields and encoding of each property the engine takes field by field.</content>")
            .AppendLine("internal static partial class SceneWire")
            .AppendLine("{")
            .AppendLine("    private static void AddSchemaMappings(global::System.Collections.Generic.Dictionary<global::Oxygen.Editor.Schemas.PropertyId, Mapping> map)")
            .AppendLine("    {");
        foreach (var component in schema.Components.Where(static component => component.Wire is not null))
        {
            var fieldEnum = "global::Oxygen.Editor.Runtime.Engine." + component.Wire!.FieldSet + "Field";
            foreach (var property in component.Properties)
            {
                var fields = string.Join(", ", property.Fields.Select(field => "(ushort)" + fieldEnum + "." + field));
                _ = source
                    .Append("        map.Add(global::Oxygen.Editor.Scenes.Properties.SceneSchema.").Append(component.Name).Append('.').Append(property.Name)
                    .Append(".Id, new Mapping(global::Oxygen.Editor.Runtime.Engine.RuntimeComponentId.").Append(component.Name)
                    .Append(", [").Append(fields).Append("])");
                _ = property.Encoding is null
                    ? source.AppendLine(");")
                    : source.Append(" { Encode = ").Append(SceneComponentsTypes.EncodingMethod(property.Encoding)).AppendLine(" });");
            }
        }

        return source.AppendLine("    }").AppendLine("}").ToString();
    }

    private static string Number(int value) => value.ToString(CultureInfo.InvariantCulture);
}
