def render(schema: Schema, source: str) -> str:
    """Returns the header text; `source` names the schema file."""
    lines = [
        LICENSE,
        f"// Generated by SceneSchemaCodeGen from {source}; do not edit.",
        "",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstdint>",
        "#include <optional>",
        "#include <span>",
        "#include <string_view>",
        "#include <utility>",
        "",
        "#include <Oxygen/Data/AssetType.h>",
        "#include <Oxygen/Data/PakFormat_geometry.h>",
        "#include <Oxygen/Data/Schema/PropertyRange.h>",
        "",
        "// The generator owns this layout.",
        "// clang-format off",
        "",
        "namespace oxygen::data::schema {",
        "",
        "//! The scene components applied field by field.",
        "enum class ComponentId : std::uint16_t {",
        "  kInvalid = 0,",
        *(f"  k{component.name} = {wire.id}," for component, wire in schema.wired()),
        "};",
    ]
    for field_set in schema.field_sets:
        lines.extend(["", *_field_enum(field_set)])
    lines.extend(["", *_field_type_enum()])
    # Fields of one value type share a branch body by design.
    lines.extend(["", "// NOLINTBEGIN(bugprone-branch-clone)"])
    for field_set in schema.field_sets:
        lines.extend(["", *_field_type_lookup(schema, field_set)])
    lines.extend(["", *_component_field_type_lookup(schema)])
    lines.extend(["", "// NOLINTEND(bugprone-branch-clone)"])
    lines.extend(["", *_value_type_enum()])
    lines.extend(["", *_part_kind_enum(schema)])
    lines.extend(["", *_encoding_enum(), "", *_member_enum()])
    lines.extend(["", *_override_table(schema)])
    for enumeration in schema.enums:
        lines.extend(["", *_enumeration_values(enumeration)])
    for component in schema.components:
        lines.extend(_component_values(schema, component))
    lines.extend(["", *_field_value_checks(schema)])
    lines.extend(
        ["", "} // namespace oxygen::data::schema", "", "// clang-format on", ""]
    )
    return "\n".join(lines)


def _field_enum(field_set: FieldSet) -> list[str]:
    return [
        f"//! Component-local field ids of the {field_set.name} field set.",
        f"enum class {field_set.name}Field : std::uint16_t {{",
        *(f"  k{field.name} = {field.id}," for field in field_set.ordered()),
        f"  kCount = {field_set.count},",
        "};",
    ]


def _field_type_enum() -> list[str]:
    return [
        "//! The value type a field receives: a bool, an int32 (an int, or the wire",
        "//! value of an enum member) or a float (a float, or one axis of a vec3).",
        "enum class FieldType : std::uint8_t {",
        *(f"  k{_pascal(name)} = {index}," for index, name in enumerate(FIELD_TYPES)),
        "};",
    ]


def _field_type_lookup(schema: Schema, field_set: FieldSet) -> list[str]:
    types = schema.field_types(field_set)
    enum = f"{field_set.name}Field"
    return [
        f"//! The value type of a field of the {field_set.name} field set, or nullopt",
        "//! for an id the set does not declare.",
        f"[[nodiscard]] constexpr auto FindFieldType(const {enum} field) noexcept",
        "  -> std::optional<FieldType>",
        "{",
        "  switch (field) {",
        *(
            f"  case {enum}::k{field.name}: "
            f"return FieldType::k{_pascal(types[field.name])};"
            for field in field_set.ordered()
        ),
        f"  case {enum}::kCount: break;",
        "  }",
        "  return std::nullopt;",
        "}",
    ]


def _component_field_type_lookup(schema: Schema) -> list[str]:
    return [
        "//! The value type of `field` of `component`, or nullopt for a component or",
        "//! field the schema does not declare.",
        "[[nodiscard]] constexpr auto FindFieldType(const ComponentId component,",
        "  const std::uint16_t field) noexcept -> std::optional<FieldType>",
        "{",
        "  switch (component) {",
        *(
            f"  case ComponentId::k{component.name}: return FindFieldType("
            f"static_cast<{wire.field_set}Field>(field));"
            for component, wire in schema.wired()
        ),
        "  case ComponentId::kInvalid: break;",
        "  }",
        "  return std::nullopt;",
        "}",
    ]


def _field_value_checks(schema: Schema) -> list[str]:
    lines = [
        "//! Whether `value` is the wire value of one of `members`.",
        "[[nodiscard]] constexpr auto IsMember(",
        "  const std::span<const std::uint8_t> members,",
        "  const std::int32_t value) noexcept -> bool",
        "{",
        "  for (const auto member : members) {",
        "    if (std::cmp_equal(member, value)) {",
        "      return true;",
        "    }",
        "  }",
        "  return false;",
        "}",
        "",
        "// Fields of one value type share a branch body by design.",
        "// NOLINTBEGIN(bugprone-branch-clone)",
    ]
    for value_type, cpp_type in (
        ("bool", "bool"),
        ("int32", "std::int32_t"),
        ("float", "float"),
    ):
        lines.extend(["", *_field_value_check(schema, value_type, cpp_type)])
    lines.extend(["", "// NOLINTEND(bugprone-branch-clone)"])
    return lines


def _field_value_check(schema: Schema, value_type: str, cpp_type: str) -> list[str]:
    cases: list[str] = []
    for component, wire in schema.wired():
        checks = [
            (field, check)
            for field, field_type, check in _field_checks(component)
            if field_type == value_type
        ]
        enum = f"{wire.field_set}Field"
        if not checks:
            cases.append(f"  case ComponentId::k{component.name}: return false;")
            continue
        cases.extend(
            [
                f"  case ComponentId::k{component.name}:",
                f"    switch (static_cast<{enum}>(field)) {{",
                *(
                    f"    case {enum}::k{field}: return {check};"
                    for field, check in checks
                ),
                "    default: return false;",
                "    }",
            ]
        )
    # A bool field accepts either value.
    unused = "[[maybe_unused]] " if value_type == "bool" else ""
    return [
        f"//! Whether `value` is a valid {cpp_type} value of `field` of `component`:",
        "//! inside the field's range or a member of its enumeration. False for a",
        "//! field the component does not declare, or one of another value type.",
        "[[nodiscard]] constexpr auto IsValidFieldValue(const ComponentId component,",
        (
            f"  const std::uint16_t field, {unused}const {cpp_type} value) "
            "noexcept -> bool"
        ),
        "{",
        "  switch (component) {",
        *cases,
        "  case ComponentId::kInvalid: break;",
        "  }",
        "  return false;",
        "}",
    ]


def _field_checks(component: Component) -> list[tuple[str, str, str]]:
    """Each wired field of `component`: its name, value type and check."""
    space = _snake(component.kind)
    checks: list[tuple[str, str, str]] = []
    for entry in component.properties:
        for field in entry.fields:
            if entry.type == "bool":
                checks.append((field, "bool", "true"))
            elif entry.type == "enum":
                checks.append(
                    (field, "int32", f"IsMember({space}::k{field}Values, value)")
                )
            elif entry.type == "int":
                checks.append(
                    (field, "int32", f"{space}::k{field}Range.Contains(value)")
                )
            else:
                checks.append(
                    (field, "float", f"{space}::k{field}Range.Contains(value)")
                )
    return checks


def _value_type_enum() -> list[str]:
    return [
        "//! The value types of the schema properties.",
        "enum class ValueType : std::uint8_t {",
        *(f"  k{name} = {index}," for index, (_, name) in enumerate(_VALUE_TYPES)),
        "};",
    ]


def _part_kind_enum(schema: Schema) -> list[str]:
    return [
        "//! The part kinds; kNone addresses the component itself.",
        "enum class PartKind : std::uint8_t {",
        "  kNone = 0,",
        *(
            f"  k{_pascal(kind)} = {index},"
            for index, kind in enumerate(schema.part_kinds(), start=1)
        ),
        "};",
    ]


def _encoding_enum() -> list[str]:
    return [
        "//! The unit conversion of a property's value before it goes to its fields.",
        "enum class Encoding : std::uint8_t {",
        "  kNone = 0,",
        *(
            f"  k{name} = {index},"
            for index, (_, name) in enumerate(_ENCODINGS, start=1)
        ),
        "};",
    ]


def _member_enum() -> list[str]:
    return [
        "//! The member of `OverrideValue` that holds a property's change.",
        "enum class ValueMember : std::uint8_t {",
        *(f"  k{name} = {index}," for index, name in enumerate(_MEMBER_NAMES)),
        "};",
    ]


def _encoding_name(entry: Property) -> str:
    return "None" if entry.encoding is None else dict(_ENCODINGS)[entry.encoding]


def _member_name(entry: Property) -> str:
    if entry.encoding == "euler-xyz-degrees-to-quat":
        return "Quat"
    return dict(_MEMBERS)[entry.type]


def _override_table(schema: Schema) -> list[str]:
    overrides = schema.overrides()
    names = {
        entry.id: override_name(entry.component, entry.part, entry.prop)
        for entry in overrides
    }
    types = dict(_VALUE_TYPES)
    rows: list[str] = []
    for entry in overrides:
        part = "kNone" if entry.part is None else f"k{_pascal(entry.part.kind)}"
        asset_type = _pascal(entry.prop.asset_type or "unknown")
        wired = entry.component.wire is not None and entry.part is None
        component = f"k{entry.component.name}" if wired else "kInvalid"
        rows.extend(
            [
                "  OverrideProperty {",
                f"    .id = OverrideId::k{names[entry.id]},",
                f'    .component_kind = "{entry.component.kind}",',
                f"    .component = ComponentId::{component},",
                f"    .part_kind = PartKind::{part},",
                f'    .key = "{entry.prop.key}",',
                f"    .type = ValueType::k{types[entry.prop.type]},",
                f"    .asset_type = AssetType::k{asset_type},",
                f"    .encoding = Encoding::k{_encoding_name(entry.prop)},",
                f"    .member = ValueMember::k{_member_name(entry.prop)},",
                f"    .asset_sourced = {_bool('asset' in entry.prop.sources)},",
                "  },",
            ]
        )
    return [
        "//! The ids of the properties a scene can change, and of those it stores as",
        "//! overrides of an asset's values. Stable: never renumbered or reused.",
        "enum class OverrideId : std::uint16_t {",
        "  kInvalid = 0,",
        *(f"  k{names[entry.id]} = {entry.id}," for entry in overrides),
        "};",
        "",
        "//! The address, value type and change encoding of a property with an",
        "//! override id. `component` is the wired component whose fields receive",
        "//! the value (kInvalid for a property applied as an override of an asset's",
        "//! value); `asset_type` is the type an asset value references (kUnknown",
        "//! otherwise); `member` is the `OverrideValue` member a change uses.",
        "//! An `asset_sourced` property takes its value from the node's asset and",
        "//! is stored as an override of it on owned nodes too; every other",
        "//! property of an owned node is stored in the node's records.",
        "struct OverrideProperty {",
        "  OverrideId id;",
        "  std::string_view component_kind;",
        "  ComponentId component;",
        "  PartKind part_kind;",
        "  std::string_view key;",
        "  ValueType type;",
        "  AssetType asset_type;",
        "  Encoding encoding;",
        "  ValueMember member;",
        "  bool asset_sourced;",
        "};",
        "",
        "//! The properties with an override id, by override id.",
        (
            f"inline constexpr std::array<OverrideProperty, {len(overrides)}> "
            "kOverrideProperties {"
        ),
        *rows,
        "};",
        "",
        "//! The override property `id` names, or null for an id the schema does not",
        "//! declare.",
        "[[nodiscard]] constexpr auto FindOverrideProperty(const OverrideId id)",
        "  noexcept -> const OverrideProperty*",
        "{",
        "  for (const auto& property : kOverrideProperties) {",
        "    if (property.id == id) {",
        "      return &property;",
        "    }",
        "  }",
        "  return nullptr;",
        "}",
        "",
        "//! The override property of `component_kind` with `key` on `part_kind`, or",
        "//! null when the schema declares none.",
        "[[nodiscard]] constexpr auto FindOverrideProperty(",
        "  const std::string_view component_kind, const PartKind part_kind,",
        "  const std::string_view key) noexcept -> const OverrideProperty*",
        "{",
        "  for (const auto& property : kOverrideProperties) {",
        "    if (property.component_kind == component_kind",
        "      && property.part_kind == part_kind && property.key == key) {",
        "      return &property;",
        "    }",
        "  }",
        "  return nullptr;",
        "}",
    ]


def override_name(component: Component, part: Part | None, entry: Property) -> str:
    return component.name + ("" if part is None else part.name) + entry.name


def _enumeration_values(enumeration: Enumeration) -> list[str]:
    values = ", ".join(str(member.value) for member in enumeration.members)
    keys = ", ".join(f'"{_member_key(member.name)}"' for member in enumeration.members)
    count = len(enumeration.members)
    name = enumeration.name
    return [
        f"//! The members of {name}, by wire value.",
        f"enum class {name} : std::uint8_t {{",
        *(f"  k{member.name} = {member.value}," for member in enumeration.members),
        "};",
        "",
        f"//! The wire values of the {name} members.",
        (
            f"inline constexpr std::array<std::uint8_t, {count}> "
            f"k{name}Members {{ {values} }};"
        ),
        "",
        f"//! The key a document spells each {name} member by, in member order.",
        (
            f"inline constexpr std::array<std::string_view, {count}> "
            f"k{name}MemberKeys {{ {keys} }};"
        ),
    ]


def _member_key(name: str) -> str:
    """The snake_case key of a PascalCase member name."""
    return "".join(
        f"_{char.lower()}" if char.isupper() and index > 0 else char.lower()
        for index, char in enumerate(name)
    )


def _component_values(schema: Schema, component: Component) -> list[str]:
    lines: list[str] = []
    for entry in component.properties:
        lines.extend(_property_values(schema, entry, component.wire is not None))
    if lines:
        lines = [
            "",
            f"//! Defaults and ranges of {component.name}, in field units.",
            f"namespace {_snake(component.kind)} {{",
            *lines,
            f"}} // namespace {_snake(component.kind)}",
        ]
    for part in component.parts:
        part_lines: list[str] = []
        for entry in part.properties:
            part_lines.extend(_property_values(schema, entry, wired=False))
        if part_lines:
            space = f"{_snake(component.kind)}::{_snake(part.kind)}"
            lines.extend(
                [
                    "",
                    (
                        f"//! Defaults and ranges of the {component.name} "
                        f"{part.name} part."
                    ),
                    f"namespace {space} {{",
                    *part_lines,
                    f"}} // namespace {space}",
                ]
            )
    return lines


def _property_values(schema: Schema, entry: Property, wired: bool) -> list[str]:
    # A wired property's values are per field, after its encoding; any other
    # property's values are the property's own.
    if entry.default is None:
        return []
    names = list(entry.fields) if wired else [entry.name]
    if entry.type == "bool":
        return [_constant("bool", f"k{names[0]}Default", _bool(entry.default))]
    if entry.type == "enum":
        return _enum_values(schema, entry, names[0])
    if isinstance(entry.default, LodPolicy):
        return _lod_policy_value(names[0], entry.default)
    return _numeric_values(entry, names)


def _enum_values(schema: Schema, entry: Property, name: str) -> list[str]:
    assert entry.enum is not None
    enumeration = schema.enumeration(entry.enum)
    lines = [
        _constant(entry.enum, f"k{name}Default", f"{entry.enum}::k{entry.default}")
    ]
    if entry.root_default is not None:
        lines.append(
            _constant(
                entry.enum,
                f"k{name}RootDefault",
                f"{entry.enum}::k{entry.root_default}",
            )
        )
    assert enumeration.value_of(str(entry.default)) is not None
    lines.append(
        f"inline constexpr std::span<const std::uint8_t> k{name}Values "
        f"{{ k{entry.enum}Members }};"
    )
    return lines


def _numeric_values(entry: Property, names: list[str]) -> list[str]:
    is_int = entry.type == "int"
    value_type = "std::int32_t" if is_int else "float"
    bounds = _encoded_range(entry)
    defaults = [_encoded(entry, value) for value in entry.components()]
    if not entry.fields:
        names = (
            [entry.name]
            if len(defaults) == 1
            else [f"{entry.name}{axis}" for axis in "XYZ"]
        )
    lines: list[str] = []
    for name, value in zip(names, defaults, strict=True):
        lines.append(
            _constant(
                value_type, f"k{name}Default", _int(value) if is_int else _float(value)
            )
        )
        lines.append(
            f"inline constexpr PropertyRange<{value_type}> k{name}Range "
            f"{_range(bounds, is_int, entry.commit == 'clamp')};"
        )
    return lines


def _lod_policy_value(name: str, policy: LodPolicy) -> list[str]:
    members = [
        f"  .type = {_PAK}::LodPolicyType::{_LOD_POLICY_TYPES[policy.type]},",
        f"  .lod_index = {policy.lod_index},",
    ]
    boundaries = policy.thresholds or policy.enter_finer_sse
    if boundaries:
        members.append(f"  .boundary_count = {len(boundaries)},")
    if policy.thresholds:
        members.append(f"  .thresholds = {{ {_floats(policy.thresholds)} }},")
        members.append(f"  .hysteresis_ratio = {_float(policy.hysteresis_ratio)},")
    if policy.enter_finer_sse:
        members.append(f"  .enter_finer_sse = {{ {_floats(policy.enter_finer_sse)} }},")
        members.append(
            f"  .exit_coarser_sse = {{ {_floats(policy.exit_coarser_sse)} }},"
        )
    return [
        f"inline constexpr {_PAK}::LodPolicyRecord k{name}Default {{",
        *members,
        "};",
    ]


def _encoded(entry: Property, value: float) -> float:
    if entry.encoding == "degrees-to-radians":
        return math.radians(value)
    return value


def _encoded_range(entry: Property) -> Range:
    bounds = entry.range or UNLIMITED
    return Range(
        min=None if bounds.min is None else _encoded(entry, bounds.min),
        max=None if bounds.max is None else _encoded(entry, bounds.max),
        min_exclusive=bounds.min_exclusive,
        max_exclusive=bounds.max_exclusive,
        nonzero=bounds.nonzero,
    )


def _range(bounds: Range, is_int: bool, clamp: bool) -> str:
    def number(value: float) -> str:
        return _int(value) if is_int else _float(value)

    members: list[str] = []
    if bounds.min is not None:
        members.append(f".min = {number(bounds.min)}")
    if bounds.max is not None:
        members.append(f".max = {number(bounds.max)}")
    if bounds.min_exclusive:
        members.append(".min_exclusive = true")
    if bounds.max_exclusive:
        members.append(".max_exclusive = true")
    if bounds.nonzero:
        members.append(".nonzero = true")
    if clamp:
        members.append(".clamp = true")
    return "{ " + ", ".join(members) + " }" if members else "{}"


def _constant(value_type: str, name: str, value: str, terminate: bool = True) -> str:
    return f"inline constexpr {value_type} {name} = {value}{';' if terminate else ''}"


def _bool(value: object) -> str:
    return "true" if value else "false"


def _int(value: float) -> str:
    return str(int(value))


def _float(value: float) -> str:
    # The shortest decimal that reads back as the same float32.
    single = struct.unpack("f", struct.pack("f", value))[0]
    for digits in range(1, 10):
        text = repr(float(f"{single:.{digits}g}"))
        if struct.unpack("f", struct.pack("f", float(text)))[0] == single:
            break
    else:
        text = repr(single)
    if not any(marker in text for marker in ".en"):
        text += ".0"
    return f"{text}F"


def _floats(values: tuple[float, ...]) -> str:
    return ", ".join(_float(value) for value in values)


def _snake(kind: str) -> str:
    return kind.replace("-", "_")


def _pascal(kind: str) -> str:
    return "".join(word.capitalize() for word in kind.split("-"))
