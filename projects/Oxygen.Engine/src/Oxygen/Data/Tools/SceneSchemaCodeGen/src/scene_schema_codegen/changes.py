"""Renders the encoder, the record appliers and the record readers of scene
changes."""

# pyright: strict

from __future__ import annotations

from .cpp import LICENSE, RECORDS, override_name
from .model import Override, Schema, SchemaError


def render(schema: Schema, source: str) -> str:
    """Returns the changes header text; `source` names the schema file."""
    overrides = schema.overrides()
    unmapped = sorted(
        {
            component.kind
            for component, _ in schema.wired()
            if component.kind not in RECORDS
        }
    )
    if unmapped:
        raise SchemaError(f"no cooked record for {', '.join(unmapped)}")
    lines = [
        LICENSE,
        f"// Generated by SceneSchemaCodeGen from {source}; do not edit.",
        "",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstdint>",
        "#include <optional>",
        "",
        "#include <Oxygen/Data/PakFormat_world.h>",
        "#include <Oxygen/Data/SceneChangeValues.h>",
        "#include <Oxygen/Data/SceneRecordFields.h>",
        "#include <Oxygen/Data/Schema/Generated.SceneComponents.h>",
        "",
        "// The generator owns this layout.",
        "// clang-format off",
        "",
        "namespace oxygen::data::schema {",
        "",
        *_encoder(overrides),
    ]
    for record in dict.fromkeys(RECORDS.values()):
        kinds = {kind for kind, name in RECORDS.items() if name == record}
        held = [
            entry
            for entry in overrides
            if entry.component.kind in kinds and entry.part is None
        ]
        lines.extend(["", *_applier(record, held), "", *_reader(record, held)])
    lines.extend(
        ["", "} // namespace oxygen::data::schema", "", "// clang-format on", ""]
    )
    return "\n".join(lines)


def _encoder(overrides: tuple[Override, ...]) -> list[str]:
    return [
        "//! The change of the property `id` names to `value`, in the property's",
        "//! schema units, or nullopt when the schema declares no such property,",
        "//! `value` is of another type or outside the property's range, or the",
        "//! property's values are not held in a change value (a LOD policy, a",
        "//! string).",
        "[[nodiscard]] inline auto EncodeChange(const OverrideId id,",
        "  const SchemaValue& value) -> std::optional<pak::world::OverrideValue>",
        "{",
        "  switch (id) {",
        *(
            f"  case OverrideId::k{_name(entry)}: return {_encode(entry)};"
            for entry in overrides
        ),
        "  case OverrideId::kInvalid: break;",
        "  }",
        "  return std::nullopt;",
        "}",
    ]


def _encode(entry: Override) -> str:
    prop = entry.prop
    wire = entry.component.wire
    if wire is None or entry.part is not None:
        if prop.type == "bool":
            return "detail::EncodeBool(value)"
        if prop.type == "asset":
            return "detail::EncodeAsset(value)"
        if prop.type in ("lod-policy", "string"):
            return "std::nullopt"
        raise SchemaError(
            f"{entry.component.name}.{prop.name}: an unwired {prop.type} property "
            "has no change encoding"
        )
    component = f"ComponentId::k{entry.component.name}"
    fields = [f"{wire.field_set}Field::k{field}" for field in prop.fields]
    ids = [f"static_cast<std::uint16_t>({field})" for field in fields]
    if prop.type == "bool":
        return "detail::EncodeBool(value)"
    if prop.type in ("int", "enum"):
        return f"detail::EncodeInt32(value, {component}, {ids[0]})"
    if prop.type == "float":
        radians = ", true" if prop.encoding == "degrees-to-radians" else ""
        return f"detail::EncodeFloat(value, {component}, {ids[0]}{radians})"
    encoder = (
        "EncodeRotation"
        if prop.encoding == "euler-xyz-degrees-to-quat"
        else "EncodeVec3"
    )
    return f"detail::{encoder}(value, {component}, {{ {', '.join(ids)} }})"


def _applier(record: str, overrides: list[Override]) -> list[str]:
    return [
        f"//! Writes the change `value` of the property `id` names into a {record};",
        "//! false, leaving the record unchanged, when the property is not one the",
        "//! record holds.",
        "[[nodiscard]] inline auto ApplyChange(",
        f"  pak::world::{record}& record, const OverrideId id,",
        "  const pak::world::OverrideValue& value) -> bool",
        "{",
        "  switch (id) {",
        *(
            f"  case OverrideId::k{_name(entry)}: {_apply(entry)}"
            for entry in overrides
        ),
        "  default: break;",
        "  }",
        "  return false;",
        "}",
    ]


def _apply(entry: Override) -> str:
    prop = entry.prop
    wire = entry.component.wire
    assert wire is not None
    fields = [f"{wire.field_set}Field::k{field}" for field in prop.fields]
    if prop.encoding == "euler-xyz-degrees-to-quat":
        quaternion = ", ".join(f"value.as_quat[{axis}]" for axis in range(4))
        return f"pak::world::WriteRotation(record, {{ {quaternion} }}); return true;"
    if prop.type == "vec3":
        vector = ", ".join(f"value.as_vec3[{axis}]" for axis in range(3))
        return (
            f"return detail::WriteVec3(record, std::array {{ {', '.join(fields)} }}, "
            f"std::array {{ {vector} }});"
        )
    member = {
        "bool": "value.as_bool != 0U",
        "int": "value.as_int32",
        "enum": "value.as_int32",
        "float": "value.as_float",
    }[prop.type]
    return f"return pak::world::WriteField(record, {fields[0]}, {member});"


def _reader(record: str, overrides: list[Override]) -> list[str]:
    return [
        f"//! The value of the property `id` names in a {record}, in the",
        "//! property's schema units; nullopt when the property is not one the",
        "//! record holds.",
        "[[nodiscard]] inline auto ReadProperty(",
        f"  const pak::world::{record}& record, const OverrideId id)",
        "  -> std::optional<SchemaValue>",
        "{",
        "  switch (id) {",
        *(
            f"  case OverrideId::k{_name(entry)}: return {_read(entry)};"
            for entry in overrides
        ),
        "  default: break;",
        "  }",
        "  return std::nullopt;",
        "}",
    ]


def _read(entry: Override) -> str:
    prop = entry.prop
    wire = entry.component.wire
    assert wire is not None
    fields = [f"{wire.field_set}Field::k{field}" for field in prop.fields]
    if prop.encoding == "euler-xyz-degrees-to-quat":
        return "detail::ReadRotation(record)"
    if prop.type == "vec3":
        return f"detail::ReadVec3(record, std::array {{ {', '.join(fields)} }})"
    if prop.encoding == "degrees-to-radians":
        return f"detail::ReadValue(record, {fields[0]}, true)"
    return f"detail::ReadValue(record, {fields[0]})"


def _name(entry: Override) -> str:
    return override_name(entry.component, entry.part, entry.prop)
