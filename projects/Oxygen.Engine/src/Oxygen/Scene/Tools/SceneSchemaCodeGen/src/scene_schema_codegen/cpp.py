"""Renders the component and field ids as a C++ header."""

# pyright: strict

from __future__ import annotations

from .model import FieldSet, Schema

_LICENSE = """\
//===----------------------------------------------------------------------===//
// Distributed under the 3-Clause BSD License. See accompanying file LICENSE or
// copy at https://opensource.org/licenses/BSD-3-Clause.
// SPDX-License-Identifier: BSD-3-Clause
//===----------------------------------------------------------------------===//
"""


def render(schema: Schema, source: str) -> str:
    """Returns the header text; `source` names the schema file."""
    lines = [
        _LICENSE,
        f"// Generated by SceneSchemaCodeGen from {source}; do not edit.",
        "",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace oxygen::scene::schema {",
        "",
        "//! The scene components applied field by field.",
        "enum class ComponentId : std::uint16_t {",
        "  kInvalid = 0,",
        *(f"  k{component.name} = {wire.id}," for component, wire in schema.wired()),
        "};",
    ]
    for field_set in schema.field_sets:
        lines.extend(["", *_field_enum(field_set)])
    lines.extend(["", "} // namespace oxygen::scene::schema", ""])
    return "\n".join(lines)


def _field_enum(field_set: FieldSet) -> list[str]:
    return [
        f"//! Component-local field ids of the {field_set.name} field set.",
        f"enum class {field_set.name}Field : std::uint16_t {{",
        *(f"  k{field.name} = {field.id}," for field in field_set.ordered()),
        f"  kCount = {field_set.count},",
        "};",
    ]
