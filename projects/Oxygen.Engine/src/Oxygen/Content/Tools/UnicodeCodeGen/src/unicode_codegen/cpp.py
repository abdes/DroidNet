"""Renders the tables as a C++ header."""

from __future__ import annotations

from collections.abc import Iterable

from .ucd import UnicodeData

_LICENSE = """\
//===----------------------------------------------------------------------===//
// Distributed under the 3-Clause BSD License. See accompanying file LICENSE or
// copy at https://opensource.org/licenses/BSD-3-Clause.
// SPDX-License-Identifier: BSD-3-Clause
//===----------------------------------------------------------------------===//
"""

_PER_LINE = 3


def _rows(entries: Iterable[str]) -> list[str]:
    items = list(entries)
    return [
        "  " + " ".join(items[index : index + _PER_LINE])
        for index in range(0, len(items), _PER_LINE)
    ]


def render(data: UnicodeData, source: str) -> str:
    """Returns the header text; `source` names the database folder."""
    assigned = _rows(
        f"{{ 0x{first:06X}, 0x{last:06X} }}," for first, last in data.assigned
    )
    folding = _rows(
        f"{{ 0x{code:06X}, 0x{folded:06X} }},"
        for code, folded in data.simple_case_folding
    )
    lines = [
        _LICENSE,
        f"// Generated by UnicodeCodeGen from {source}; do not edit.",
        "",
        "#pragma once",
        "",
        "#include <array>",
        "#include <string_view>",
        "",
        "namespace oxygen::content::internal::unicode {",
        "",
        "struct CodePointRange {",
        "  char32_t first;",
        "  char32_t last;",
        "};",
        "",
        "struct CaseFoldingPair {",
        "  char32_t code;",
        "  char32_t folded;",
        "};",
        "",
        "//! Unicode version of the tables.",
        f'inline constexpr std::string_view kVersion = "{data.version}";',
        "",
        "//! Assigned code points (DerivedAge.txt), merged ranges in order.",
        "// clang-format off",
        "inline constexpr auto kAssigned = std::array<CodePointRange, "
        f"{len(data.assigned)}> {{ {{",
        *assigned,
        "} };",
        "// clang-format on",
        "",
        "//! Simple case folding (CaseFolding.txt, status C and S), by code.",
        "// clang-format off",
        "inline constexpr auto kSimpleCaseFolding = std::array<CaseFoldingPair, "
        f"{len(data.simple_case_folding)}> {{ {{",
        *folding,
        "} };",
        "// clang-format on",
        "",
        "} // namespace oxygen::content::internal::unicode",
        "",
    ]
    return "\n".join(lines)
